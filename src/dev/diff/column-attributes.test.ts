import { beforeEach, describe, expect, it } from "vitest";
import { useTestDatabase } from "../../adapters/postgres-js/test-database.test-helper.ts";
import {
  catalogBuilder,
  type Catalog,
  type CatalogBuilder,
  type ColumnPayload,
  type DefaultPayload,
  type IdentityPayload,
} from "../catalog/index.ts";
import { introspect } from "../introspect/index.ts";
import { diff } from "./diff.ts";

const db = useTestDatabase();

type Column = {
  readonly type?: string;
  readonly notNull?: boolean;
  readonly default?: DefaultPayload;
  readonly identity?: IdentityPayload;
};

/** A `public.t` table with the given columns, each followed by its default and identity facts. */
function table(columns: Readonly<Record<string, Column>>): Catalog {
  const builder: CatalogBuilder = catalogBuilder();
  builder.schema("public");
  builder.table("public", "t");
  for (const [name, column] of Object.entries(columns)) {
    const payload: ColumnPayload = {
      type: column.type ?? "text",
      notNull: column.notNull ?? false,
    };
    builder.column("public", "t", name, payload);
    if (column.identity !== undefined) builder.columnIdentity("public", "t", name, column.identity);
    if (column.default !== undefined) builder.columnDefault("public", "t", name, column.default);
  }
  return builder.build();
}

const always = { generated: "always" } as const;
const byDefault = { generated: "by default" } as const;

beforeEach(async () => {
  await db.driver.execute("drop schema public cascade; create schema public");
});

describe("create table and add column", () => {
  it("renders NOT NULL, identity, and default inline", () => {
    const to = table({
      id: { type: "integer", notNull: true, identity: always },
      role: { default: { expression: "'member'::text" } },
      at: { type: "timestamp with time zone", notNull: true, default: { expression: "now()" } },
    });
    const from = catalogBuilder();
    from.schema("public");

    expect(diff(from.build(), to)).toBe(`create table "public"."t" (
  "id" integer not null generated always as identity,
  "role" text default ('member'::text),
  "at" timestamp with time zone not null default (now())
);
`);
  });

  it("adds a column to an existing table with its attributes and no separate alter", () => {
    const from = table({ id: {} });
    const to = table({
      id: {},
      n: { type: "bigint", notNull: true, identity: byDefault },
      role: { default: { expression: "'x'::text" } },
    });

    expect(diff(from, to))
      .toBe(`alter table "public"."t" add column "n" bigint not null generated by default as identity;

alter table "public"."t" add column "role" text default ('x'::text);
`);
  });

  it("wraps a default in parentheses, so any expression parses", () => {
    const to = table({ flag: { type: "boolean", default: { expression: "true and false" } } });
    expect(diff(table({}), to)).toContain(`default (true and false)`);
  });
});

describe("alters", () => {
  it("sets and drops NOT NULL", () => {
    const from = table({ a: {}, b: { notNull: true } });
    const to = table({ a: { notNull: true }, b: {} });

    expect(diff(from, to)).toBe(`alter table "public"."t" alter column "a" set not null;

alter table "public"."t" alter column "b" drop not null;
`);
  });

  it("sets, changes, and drops a default", () => {
    const from = table({ a: {}, b: { default: { expression: "'x'::text" } }, c: {} });
    const to = table({
      a: { default: { expression: "'a'::text" } },
      b: { default: { expression: "'y'::text" } },
      c: {},
    });
    const dropped = table({ a: {}, b: {}, c: {} });

    expect(diff(from, to)).toBe(`alter table "public"."t" alter column "a" set default ('a'::text);

alter table "public"."t" alter column "b" set default ('y'::text);
`);
    expect(diff(from, dropped)).toBe(`alter table "public"."t" alter column "b" drop default;\n`);
  });

  it("adds and drops identity", () => {
    const withIdentity = table({ id: { type: "integer", notNull: true, identity: always } });
    const without = table({ id: { type: "integer", notNull: true } });

    expect(diff(without, withIdentity)).toBe(
      `alter table "public"."t" alter column "id" add generated always as identity;\n`,
    );
    expect(diff(withIdentity, without)).toBe(
      `alter table "public"."t" alter column "id" drop identity;\n`,
    );
  });

  it("refuses to change how an identity is generated", () => {
    const from = table({ id: { type: "integer", notNull: true, identity: always } });
    const to = table({ id: { type: "integer", notNull: true, identity: byDefault } });

    expect(() => diff(from, to)).toThrow(`Can't alter identity of column "public"."t"."id" yet`);
  });

  it("changes a type with a plain ALTER COLUMN ... TYPE, before NOT NULL", () => {
    expect(diff(table({ a: { type: "text" } }), table({ a: { type: "integer", notNull: true } })))
      .toBe(`alter table "public"."t" alter column "a" type integer;

alter table "public"."t" alter column "a" set not null;
`);
  });

  it("drops a default before a type change and sets it again afterward", () => {
    const from = table({ a: { type: "integer", default: { expression: "1" } } });
    const to = table({ a: { type: "bigint", default: { expression: "1" } } });

    expect(diff(from, to).split("\n\n")).toStrictEqual([
      `alter table "public"."t" alter column "a" drop default;`,
      `alter table "public"."t" alter column "a" type bigint;`,
      `alter table "public"."t" alter column "a" set default (1);\n`,
    ]);
  });

  it("drops the old default and sets the new one around a type change", () => {
    const from = table({ a: { type: "integer", default: { expression: "1" } } });
    const to = table({ a: { type: "text", default: { expression: "'one'::text" } } });

    expect(diff(from, to).split("\n\n")).toStrictEqual([
      `alter table "public"."t" alter column "a" drop default;`,
      `alter table "public"."t" alter column "a" type text;`,
      `alter table "public"."t" alter column "a" set default ('one'::text);\n`,
    ]);
  });

  it("drops a default, or sets one, only once around a type change", () => {
    const from = table({ a: { type: "integer", default: { expression: "1" } }, b: {} });
    const to = table({
      a: { type: "bigint" },
      b: { type: "character varying(20)", default: { expression: "'b'::character varying" } },
    });

    expect(diff(from, to).split("\n\n")).toStrictEqual([
      `alter table "public"."t" alter column "a" drop default;`,
      `alter table "public"."t" alter column "a" type bigint;`,
      `alter table "public"."t" alter column "b" type character varying(20);`,
      `alter table "public"."t" alter column "b" set default ('b'::character varying);\n`,
    ]);
  });

  it("drops a column alone, without its default first", () => {
    const from = table({ a: { default: { expression: "'x'::text" } } });
    expect(diff(from, table({}))).toBe(`alter table "public"."t" drop column "a";\n`);
  });

  it("orders drops of defaults and identity before NOT NULL, and sets after", () => {
    const from = table({
      a: { type: "integer", notNull: true, identity: always },
      b: { type: "integer", default: { expression: "1" } },
      c: { type: "integer", notNull: true, default: { expression: "2" } },
      d: {},
    });
    const to = table({
      a: { type: "integer" },
      b: { type: "integer", notNull: true, identity: byDefault },
      c: { type: "integer", notNull: true, default: { expression: "3" } },
      d: { default: { expression: "'d'::text" }, notNull: true },
    });

    expect(diff(from, to).split("\n\n")).toStrictEqual([
      `alter table "public"."t" alter column "b" drop default;`,
      `alter table "public"."t" alter column "a" drop identity;`,
      `alter table "public"."t" alter column "a" drop not null;`,
      `alter table "public"."t" alter column "b" set not null;`,
      `alter table "public"."t" alter column "d" set not null;`,
      `alter table "public"."t" alter column "c" set default (3);`,
      `alter table "public"."t" alter column "d" set default ('d'::text);`,
      `alter table "public"."t" alter column "b" add generated by default as identity;\n`,
    ]);
  });
});

describe("against Postgres", () => {
  it("creates a table with every attribute and introspects back with no remaining diff", async () => {
    const wanted = table({
      id: { type: "integer", notNull: true, identity: always },
      n: { type: "bigint", notNull: true, identity: byDefault },
      role: { default: { expression: "'member'::text" } },
      at: { type: "timestamp with time zone", notNull: true, default: { expression: "now()" } },
      score: { type: "integer", default: { expression: "(1 + 2)" } },
    });

    await db.driver.execute(diff(await introspect(db.driver), wanted));

    const actual = await introspect(db.driver);
    expect(diff(actual, wanted)).toBe("");
    expect(actual).toStrictEqual(wanted);
  });

  it("adds columns with attributes to an existing table", async () => {
    await db.driver.execute("create table t (id text)");
    const wanted = table({
      id: {},
      n: { type: "bigint", notNull: true, identity: always },
      role: { notNull: true, default: { expression: "'member'::text" } },
    });

    await db.driver.execute(diff(await introspect(db.driver), wanted));

    expect(await introspect(db.driver)).toStrictEqual(wanted);
  });

  it("alters every attribute of existing columns, keeping Postgres's rules about order", async () => {
    await db.driver.execute(`
      create table t (
        a text,
        b text not null,
        c text default 'x',
        d text default 'y',
        e integer generated always as identity,
        f integer default 5,
        g integer generated by default as identity,
        h text not null default 'h',
        i integer generated always as identity
      )`);
    const wanted = table({
      a: { notNull: true },
      b: {},
      c: {},
      d: { default: { expression: "'z'::text" } },
      e: { type: "integer" },
      f: { type: "integer", notNull: true, identity: byDefault },
      g: { type: "integer", notNull: true, default: { expression: "7" } },
      h: { default: { expression: "'h'::text" } },
      i: { type: "integer", notNull: true, identity: always },
    });

    const sql = diff(await introspect(db.driver), wanted);
    await db.driver.execute(sql);

    expect(await introspect(db.driver)).toStrictEqual(wanted);
    expect(diff(await introspect(db.driver), wanted)).toBe("");
  });

  it("changes types of columns with defaults and identities, leaving no remaining diff", async () => {
    await db.driver.execute(`
      create table t (
        a character varying(5) default 'ab',
        b integer generated always as identity,
        c integer not null default 1
      )`);
    // Retyped in place, `a` would keep its default as `'ab'::character varying`.
    const wanted = table({
      a: { default: { expression: "'ab'::text" } },
      b: { type: "bigint", notNull: true, identity: always },
      c: { type: "bigint", notNull: true, default: { expression: "2" } },
    });

    await db.driver.execute(diff(await introspect(db.driver), wanted));

    expect(await introspect(db.driver)).toStrictEqual(wanted);
  });

  it("reads a NOT NULL constraint named by the user the same as an unnamed one", async () => {
    await db.driver.execute("create table t (a text constraint a_required not null)");

    expect(diff(await introspect(db.driver), table({ a: { notNull: true } }))).toBe("");
  });
});
