import { beforeEach, describe, expect, it } from "vitest";
import { useTestDatabase } from "../../adapters/postgres-js/test-database.test-helper.ts";
import { defineDatabase, defineTable } from "../../runtime/definition/index.ts";
import { DEFAULT_TRACKING_SCHEMA, trackingSchema } from "../../runtime/internal/index.ts";
import type { Session } from "../../runtime/ports/index.ts";
import { definitionCatalog, namesOf, type Catalog } from "../catalog/index.ts";
import { introspect } from "./introspect.ts";

const db = useTestDatabase();

function dottedNames(catalog: Catalog): string[] {
  return [...catalog.values()].map((fact) => namesOf(catalog, fact).join("."));
}

beforeEach(async () => {
  await db.driver.execute(`
    drop extension if exists hstore;
    drop schema if exists auth, smonn_db, ext cascade;
    drop schema public cascade;
    create schema public;
  `);
});

describe("introspect", () => {
  it("reads the same facts the Definition asks for", async () => {
    await db.driver.execute(`
      create schema auth;
      create table auth.users (id text not null, email text);
      create table auth.empty ();
      create table auth."users.email" (id text);
    `);
    const definition = defineDatabase({
      public: {},
      auth: {
        users: defineTable((c) => ({ id: c.text().notNull(), email: c.text() })),
        empty: defineTable(() => ({})),
        "users.email": defineTable((c) => ({ id: c.text() })),
      },
    });

    const catalog = await introspect(db.driver);

    expect(new Map([...catalog].toSorted(([a], [b]) => a.localeCompare(b)))).toStrictEqual(
      new Map([...definitionCatalog(definition)].toSorted(([a], [b]) => a.localeCompare(b))),
    );
    const named = [...catalog.values()].map((f) => `${f.kind} ${namesOf(catalog, f).join(".")}`);
    expect(named).toEqual(
      expect.arrayContaining(["column auth.users.email", "table auth.users.email"]),
    );
  });

  it("reads every v0.1 column type as the Definition names it", async () => {
    await db.driver.execute(`
      create table everything (
        a text, b varchar(20), c smallint, d integer, e bigint, f numeric, g numeric(10),
        h numeric(10,2), i real, j double precision, k boolean, l uuid, m date, n timestamp,
        o timestamptz, p jsonb, q bytea not null
      )`);
    const definition = defineDatabase({
      public: {
        everything: defineTable((c) => ({
          a: c.text(),
          b: c.varchar(20),
          c: c.smallint(),
          d: c.integer(),
          e: c.bigint(),
          f: c.numeric(),
          g: c.numeric(10),
          h: c.numeric(10, 2),
          i: c.real(),
          j: c.doublePrecision(),
          k: c.boolean(),
          l: c.uuid(),
          m: c.date(),
          n: c.timestamp(),
          o: c.timestamptz(),
          p: c.jsonb(),
          q: c.bytea().notNull(),
        })),
      },
    });

    expect(await introspect(db.driver)).toStrictEqual(definitionCatalog(definition));
  });

  it("reads defaults and identity as facts under their column", async () => {
    await db.driver.execute(`
      create table t (
        id integer generated always as identity,
        n bigint generated by default as identity,
        role text default 'member',
        at timestamptz not null default now(),
        plain text,
        doubled integer generated always as (n * 2) stored
      )`);

    const catalog = await introspect(db.driver);

    const facts = [...catalog.values()]
      .filter((fact) => ["default", "identity"].includes(fact.kind))
      .map((fact) => [namesOf(catalog, fact).join("."), fact.payload]);
    expect(facts).toStrictEqual([
      ["public.t.id.identity", { generated: "always" }],
      ["public.t.n.identity", { generated: "by default" }],
      ["public.t.role.default", { expression: "'member'::text" }],
      ["public.t.at.default", { expression: "now()" }],
    ]);
  });

  it("folds a Postgres 18 NOT NULL constraint into its column, whatever its name", async () => {
    await db.driver.execute(`
      create table t (
        a text not null,
        b text constraint b_required not null,
        c text,
        d text,
        e integer generated always as identity
      );
      alter table t add constraint d_required not null d not valid;
    `);

    const catalog = await introspect(db.driver);

    const columns = [...catalog.values()]
      .filter((fact) => fact.kind === "column")
      .map((fact) => [fact.name, fact.payload.notNull]);
    expect(columns).toStrictEqual([
      ["a", true],
      ["b", true],
      ["c", false],
      ["d", true],
      ["e", true],
    ]);
    expect([...catalog.values()].map((fact) => fact.kind)).not.toContain("constraint");
  });

  it("reads primary keys in key order and single-column unique constraints, and no others", async () => {
    await db.driver.execute(`
      create table t (
        a text not null, b text not null, c text, d text, e text, f text
      );
      alter table t add constraint pk primary key (b, a);
      alter table t add constraint c_uq unique (c);
      alter table t add constraint d_uq unique (d);
      alter table t add constraint ef_uq unique (e, f);
      alter table t add constraint f_check check (f <> '');
      create unique index d_index on t (d);
      create table keyless (a text);
      create table parted (a text not null, primary key (a)) partition by list (a);
      create table parted_1 partition of parted for values in ('x');
    `);

    const catalog = await introspect(db.driver);

    const keys = [...catalog.values()]
      .filter((fact) => ["primary key", "unique"].includes(fact.kind))
      .map((fact) => [fact.kind, namesOf(catalog, fact).join("."), fact.payload]);
    expect(keys).toStrictEqual([
      ["unique", "public.t.c_uq", { column: "c" }],
      ["unique", "public.t.d_uq", { column: "d" }],
      ["primary key", "public.t.pk", { columns: ["b", "a"] }],
    ]);
  });

  it("fetches no table or column of a skipped schema", async () => {
    await db.driver.execute(`
      create table kept (a text);
      create schema ${DEFAULT_TRACKING_SCHEMA};
      create table ${DEFAULT_TRACKING_SCHEMA}.current (hash text not null);
    `);
    const fetched: unknown[] = [];
    const watching: Session = {
      ...db.driver,
      transaction: (fn) =>
        db.driver.transaction((tx) =>
          fn({
            execute: (script) => tx.execute(script),
            query: async (text, params) => {
              const result = await tx.query(text, params);
              fetched.push(...result.rows.map((row) => row["schema"]));
              return result;
            },
          }),
        ),
    };

    await introspect(watching);

    expect(fetched).toContain("public");
    expect(fetched).not.toContain("pg_catalog");
    expect(fetched).not.toContain("information_schema");
    expect(fetched).not.toContain(DEFAULT_TRACKING_SCHEMA);
  });

  it("lists columns in table order", async () => {
    await db.driver.execute("create table t (b text, a text, c text); alter table t drop column a");
    expect(dottedNames(await introspect(db.driver))).toStrictEqual([
      "public",
      "public.t",
      "public.t.b",
      "public.t.c",
    ]);
  });

  it("skips the tracking schema, extension members, and views", async () => {
    await db.driver.execute(`
      create schema smonn_db;
      create table smonn_db.current (hash text not null);
      create extension hstore;
      create schema ext;
      create table ext.owned (a text);
      alter extension hstore add schema ext;
      alter extension hstore add table ext.owned;
      create table public.kept (a text);
      create view public.v as select 1 as one;
    `);

    expect(dottedNames(await introspect(db.driver))).toStrictEqual([
      "public",
      "public.kept",
      "public.kept.a",
    ]);
  });

  it("skips a configured tracking schema and keeps smonn_db", async () => {
    await db.driver.execute(`
      drop schema if exists "AppTracking" cascade;
      create schema "AppTracking";
      create table "AppTracking".current (hash text not null);
      create schema smonn_db;
    `);

    expect(dottedNames(await introspect(db.driver, trackingSchema("AppTracking")))).toStrictEqual([
      "public",
      "smonn_db",
    ]);
  });
});
