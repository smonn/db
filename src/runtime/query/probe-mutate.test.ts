// PROBE (#657, #672): the decided update and delete shapes and the alternatives, against Postgres.
/* oxlint-disable max-lines, unicorn/consistent-function-scoping, typescript/no-unsafe-call, typescript/no-unsafe-return -- PROBE: one file holds every shape, and the misuse calls are the point. */
import { beforeEach, describe, expect, expectTypeOf, it } from "vitest";
import { useTestDatabase } from "../../adapters/postgres-js/test-database.test-helper.ts";
import { defineDatabase, defineTable, type Codec } from "../definition/index.ts";
import { createClient } from "./client.ts";
import { deleteFrom, update } from "./probe-mutate.ts";
import {
  allRows,
  deleteFromMessage,
  deleteFromRow,
  deleteWhere,
  updateAlias,
  updateExplain,
  updateLoose,
  updateNever,
  updateWhere,
} from "./probe-mutate-alt.ts";

const testDatabase = useTestDatabase();
const client = createClient(testDatabase.driver);

type Day = { readonly iso: string };
const day: Codec<string, Day> = {
  decode: (base) => ({ iso: base }),
  encode: (value) => {
    if (value.iso === "bad") throw new Error("bad day");
    return value.iso;
  },
};

const db = defineDatabase({
  public: {
    users: defineTable((c) => ({
      id: c.integer().identity("always").primaryKey(),
      email: c.text().notNull(),
      name: c.text(),
      born: c.date().codec(day),
    })),
    counters: defineTable((c) => ({
      id: c.integer().identity().primaryKey(),
      n: c.integer().notNull(),
    })),
  },
});
const { users, counters } = db.public;

beforeEach(async () => {
  await testDatabase.driver.execute(`
    drop table if exists public.users, public.counters;
    create table public.users (
      id integer generated always as identity primary key,
      email text not null,
      name text,
      born date
    );
    create table public.counters (id integer generated by default as identity primary key, n integer not null);
    insert into public.users (email, name, born) values
      ('a@example.com', 'Ann', '2000-01-01'),
      ('b@example.com', null, null),
      ('c@example.com', 'Cy', '1990-05-05');
    insert into public.counters (n) values (1), (2);
  `);
});

describe("identity mode in the column type", () => {
  it("carries always, by default, a default, or nothing", () => {
    expectTypeOf<(typeof users.columns.id)["~types"]["generated"]>().toEqualTypeOf<"always">();
    expectTypeOf<
      (typeof counters.columns.id)["~types"]["generated"]
    >().toEqualTypeOf<"by default">();
    expectTypeOf<(typeof users.columns.email)["~types"]["generated"]>().toEqualTypeOf<false>();
    const t = defineTable((c) => ({ at: c.timestamptz().default("now()") }));
    expectTypeOf<(typeof t.columns.at)["~types"]["generated"]>().toEqualTypeOf<true>();
  });
});

describe("decided: update(t).set({...}).where(...)", () => {
  it("types set as every column but identity always, each optional, null only where nullable", () => {
    type UsersSet = Parameters<ReturnType<typeof update<typeof users>>["set"]>[0];
    expectTypeOf<UsersSet>().toEqualTypeOf<{
      email?: string;
      name?: string | null;
      born?: Day | null;
    }>();
    type CountersSet = Parameters<ReturnType<typeof update<typeof counters>>["set"]>[0];
    expectTypeOf<CountersSet>().toEqualTypeOf<{ id?: number; n?: number }>();
  });

  it("refuses each bad set at compile time", () => {
    // @ts-expect-error M6 an unknown key
    expect(() => update(users).set({ nope: 1 })).toThrow(
      '"nope" is not a column of "public"."users"',
    );
    // @ts-expect-error M7 null on a NOT NULL column
    update(users).set({ email: null });
    // @ts-expect-error M8 an identity-always column
    expect(() => update(users).set({ id: 5 })).toThrow(
      `update can't set "id" of "public"."users": it is generated always`,
    );
    // @ts-expect-error M9 a wrong value type
    update(users).set({ email: 5 });
    // @ts-expect-error M13 exactOptionalPropertyTypes refuses an explicit undefined
    update(users).set({ email: "x", name: undefined });
  });

  it("renders set, encodes through codecs, and combines repeated where with and", () => {
    const statement = update(users)
      .set({ name: "Bo", born: { iso: "2001-02-03" } })
      .where((u) => u.email.eq("a@example.com"))
      .where((u) => u.id.gt(0));
    expect(statement.toSql()).toStrictEqual({
      text: 'update "public"."users" set "name" = $1, "born" = $2 where ("email" = $3 and "id" > $4)',
      params: ["Bo", "2001-02-03", "a@example.com", 0],
    });
  });

  it("skips an undefined value, and throws when nothing is left to set", () => {
    const row: { email: string; name?: string } = { email: "z@example.com" };
    expect(update(users).set(row).allRows().toSql().text).toBe(
      'update "public"."users" set "email" = $1',
    );
    expect(() => update(users).set({})).toThrow("update needs at least one column to set");
    const empty = { name: undefined };
    // @ts-expect-error -- a JavaScript caller can pass undefined
    expect(() => update(users).set(empty)).toThrow("update needs at least one column to set");
  });

  it("runs on Postgres: client.one on a key where returns the new row, decoded", async () => {
    const row = await client.one(
      update(users)
        .set({ name: "Bo", born: { iso: "2001-02-03" } })
        .where((u) => u.id.eq(1))
        .returning((u) => ({ id: u.id, name: u.name, born: u.born })),
    );
    expectTypeOf(row).toEqualTypeOf<{ id: number; name: string | null; born: Day | null }>();
    expect(row).toStrictEqual({ id: 1, name: "Bo", born: { iso: "2001-02-03" } });
  });

  it("runs on Postgres: client.one is the not-found check", async () => {
    const missing = update(users)
      .set({ name: "Bo" })
      .where((u) => u.id.eq(99))
      .returning((u) => ({ id: u.id }));
    await expect(client.one(missing)).rejects.toThrow("Expected one row but the query returned 0");
  });

  it("runs on Postgres: client.run counts, allRows changes every row", async () => {
    expect(await client.run(update(counters).set({ n: 7 }).allRows())).toStrictEqual({ count: 2 });
    const rows = await client.all(
      update(counters)
        .set({ n: 8 })
        .allRows()
        .returning((c) => ({ n: c.n })),
    );
    expect(rows).toStrictEqual([{ n: 8 }, { n: 8 }]);
  });

  it("runs on Postgres: a by-default identity column can be set", async () => {
    const statement = update(counters)
      .set({ id: 10 })
      .where((c) => c.id.eq(1));
    expect(await client.run(statement)).toStrictEqual({ count: 1 });
  });

  it("runs on Postgres: a throwing codec rejects the query, not the builder", async () => {
    const statement = update(users)
      .set({ born: { iso: "bad" } })
      .allRows();
    await expect(client.run(statement)).rejects.toThrow(
      'The codec of column "born" of "public"."users" threw while encoding a value',
    );
  });
});

describe("decided: deleteFrom(t).where(...)", () => {
  it("runs on Postgres: delete where returning gives the deleted rows", async () => {
    const rows = await client.all(
      deleteFrom(users)
        .where((u) => u.name.isNull())
        .returning((u) => ({ email: u.email })),
    );
    expect(rows).toStrictEqual([{ email: "b@example.com" }]);
    const one = await client.one(
      deleteFrom(users)
        .where((u) => u.id.eq(1))
        .returning((u) => ({ id: u.id, born: u.born })),
    );
    expect(one).toStrictEqual({ id: 1, born: { iso: "2000-01-01" } });
    expect(await client.run(deleteFrom(users).allRows())).toStrictEqual({ count: 1 });
  });

  it("refuses an unfiltered statement at run time for a JavaScript caller", async () => {
    const unfiltered: unknown = deleteFrom(users);
    // oxlint-disable-next-line typescript/no-unsafe-type-assertion -- the JavaScript caller's view.
    await expect(client.run(unfiltered as never)).rejects.toThrow(
      "deleteFrom needs where() or allRows() before it runs",
    );
    const noWhere: unknown = update(users).set({ name: "x" });
    // oxlint-disable-next-line typescript/no-unsafe-type-assertion -- the JavaScript caller's view.
    await expect(client.run(noWhere as never)).rejects.toThrow(
      "update needs where() or allRows() before it runs",
    );
  });

  it("refuses each misuse at compile time", () => {
    const filtered = deleteFrom(users).where((u) => u.id.eq(1));
    const every = update(users).set({ name: "x" }).allRows();
    const marks = (): void => {
      // @ts-expect-error M1 no where or allRows
      void client.run(deleteFrom(users));
      // @ts-expect-error M2 no where or allRows after set
      void client.run(update(users).set({ name: "x" }));
      // @ts-expect-error M3 allRows carries ~many
      void client.one(every.returning((u) => ({ id: u.id })));
      const unreturned = update(users)
        .set({ name: "x" })
        .where((u) => u.id.eq(1));
      // @ts-expect-error M4 no returning: client.all can't take it
      void client.all(unreturned);
      // @ts-expect-error M5 no returning: client.one can't take it
      void client.one(filtered);
    };
    expect(marks).toBeTypeOf("function");
    expectTypeOf(every).not.toHaveProperty("where");
    expectTypeOf(filtered).not.toHaveProperty("allRows");
    expectTypeOf(deleteFrom(users)).not.toHaveProperty("returning");
    expectTypeOf(deleteFrom(users)).not.toHaveProperty("toSql");
  });
});

describe("alt A: the where is a required argument, allRows a sentinel", () => {
  it("runs on Postgres with the same SQL", async () => {
    const statement = deleteWhere(users, (u) => u.id.eq(2));
    expect(statement.toSql().text).toBe('delete from "public"."users" where "id" = $1');
    expect(await client.run(statement)).toStrictEqual({ count: 1 });
    const row = await client.one(
      updateWhere(users, (u) => u.id.eq(1))
        .set({ name: "Al" })
        .returning((u) => ({ name: u.name })),
    );
    expect(row).toStrictEqual({ name: "Al" });
    expect(await client.run(updateWhere(counters, allRows).set({ n: 0 }))).toStrictEqual({
      count: 2,
    });
    expect(await client.run(deleteWhere(users, allRows))).toStrictEqual({ count: 2 });
  });

  it("refuses each misuse at compile time", () => {
    const marks = (): void => {
      // @ts-expect-error A1 no where
      void client.run(deleteWhere(users));
      // @ts-expect-error A2 allRows carries ~many
      void client.one(deleteWhere(users, allRows).returning((u) => ({ id: u.id })));
      // @ts-expect-error A3 no set
      void client.run(updateWhere(users, (u) => u.id.eq(1)));
    };
    expect(marks).toBeTypeOf("function");
  });
});

describe("alt B-D: other set types", () => {
  it("B keeps an identity-always key typed never", () => {
    // @ts-expect-error B1 an identity-always column
    expect(() => updateNever(users).set({ id: 5 })).toThrow("it is generated always");
  });

  it("C puts the mapped type behind an alias", () => {
    // @ts-expect-error C1 an unknown key
    expect(() => updateAlias(users).set({ nope: 1 })).toThrow('"nope" is not a column');
    // @ts-expect-error C2 an identity-always column
    expect(() => updateAlias(users).set({ id: 5 })).toThrow("it is generated always");
  });

  it("D compiles an identity-always key and refuses it only at run time", () => {
    expect(() => updateLoose(users).set({ id: 5 })).toThrow("it is generated always");
  });
});

describe("alt B2: an identity-always key as a message key", () => {
  it("names the key and why in the excess-key error, and keeps the decided set otherwise", async () => {
    // @ts-expect-error B2 an identity-always column
    expect(() => updateExplain(users).set({ id: 5 })).toThrow("it is generated always");
    // @ts-expect-error B3 an unknown key
    expect(() => updateExplain(users).set({ nope: 1 })).toThrow('"nope" is not a column');
    // @ts-expect-error B4 null on a NOT NULL column
    updateExplain(users).set({ email: null });
    const statement = updateExplain(users)
      .set({ name: "Bea" })
      .where((u) => u.id.eq(3));
    expect(await client.run(statement)).toStrictEqual({ count: 1 });
  });
});

describe("alt H: builder types over the row, not the Table", () => {
  it("runs the same and prints the row in errors", async () => {
    const rows = await client.all(
      deleteFromRow(users)
        .where((u) => u.name.isNull())
        .returning((u) => ({ id: u.id })),
    );
    expect(rows).toStrictEqual([{ id: 2 }]);
    const marks = (): void => {
      // @ts-expect-error H1 no where or allRows
      void client.run(deleteFromRow(users));
      // @ts-expect-error H2 no returning: client.all can't take it
      void client.all(deleteFromRow(users).where((u) => u.id.eq(1)));
      const everyRow = deleteFromRow(users)
        .allRows()
        .returning((u) => ({ id: u.id }));
      // @ts-expect-error H3 allRows carries ~many
      void client.one(everyRow);
      // @ts-expect-error H4 isNull on a NOT NULL column stays hidden
      void deleteFromRow(users).where((u) => u.email.isNull());
    };
    expect(marks).toBeTypeOf("function");
  });
});

describe("alt E: a message in place of toSql", () => {
  it("still refuses client.run at compile time", () => {
    const marks = (): void => {
      // @ts-expect-error E1 no where or allRows
      void client.run(deleteFromMessage(users));
    };
    expect(marks).toBeTypeOf("function");
  });
});
