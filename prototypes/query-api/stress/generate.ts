// Writes stress/generated.ts: a Database far larger than v0.1 needs, and many
// queries against it, so the type-check timing measures inference, not startup.

import { writeFileSync } from "node:fs";

const TABLES = 20;
const COLUMNS = 40;
const QUERIES_PER_TABLE = 10;

const types = [
  ["text()", '"x"'],
  ["integer().notNull()", "1"],
  ["bigint()", "1n"],
  ["timestamptz().notNull()", "new Date()"],
  ["boolean()", "true"],
  ["uuid().notNull()", '"u"'],
  ["numeric(12, 2)", '"1.00"'],
  ["jsonb<{ a: number }>()", "{ a: 1 }"],
] as const;

const typeOf = (i: number) => types[i % types.length]!;

const required = Array.from({ length: COLUMNS }, (_, i) => i)
  .filter((i) => typeOf(i)[0].includes("notNull"))
  .map((i) => `c${i}: ${typeOf(i)[1]}`);
const newRow = `{ id: "u", ${required.join(", ")} }`;

let out = `// Generated by stress/generate.ts. Do not edit.
import * as A from "../a-query-values/lib.ts";
import * as B from "../b-bound-client/lib.ts";
import { defineDatabase, defineTable } from "../definition.ts";
import type { Driver } from "../query.ts";

declare const driver: Driver;
const client = A.createClient(driver);
const bound = B.connect(driver);
`;

for (let t = 0; t < TABLES; t++) {
  out += `\nconst t${t} = defineTable((c) => ({\n  id: c.uuid().primaryKey(),\n`;
  for (let i = 0; i < COLUMNS; i++) out += `  c${i}: c.${typeOf(i)[0]},\n`;
  out += "}));\n";
}

out += `\nconst db = defineDatabase({ public: { ${Array.from({ length: TABLES }, (_, t) => `t${t}`).join(", ")} } });\n`;

for (let t = 0; t < TABLES; t++) {
  for (let q = 0; q < QUERIES_PER_TABLE; q++) {
    const [a, b, c] = [q % COLUMNS, (q + 1) % COLUMNS, (q + 9) % COLUMNS];
    out += `export const a${t}_${q} = await client.all(A.from(db.public.t${t}).where((r) => r.c${a}.eq(${typeOf(a)[1]}).and(r.c${b}.ne(${typeOf(b)[1]}))).select((r) => ({ id: r.id, x: r.c${a}, y: r.c${b}, z: r.c${c} })));\n`;
    out += `export const b${t}_${q} = await bound.from(db.public.t${t}).where((r, { or }) => or(r.c${a}.eq(${typeOf(a)[1]}), r.c${c}.eq(${typeOf(c)[1]}))).select("id", "c${a}", "c${b}");\n`;
  }
  out += `export const i${t} = await client.one(A.insert(db.public.t${t}).values(${newRow}).returning("id"));\n`;
  out += `export const j${t} = await bound.insert(db.public.t${t}).values([${newRow}]);\n`;
}

writeFileSync(new URL("generated.ts", import.meta.url), out);
console.log(`wrote ${TABLES} tables x ${COLUMNS} columns, ${TABLES * (QUERIES_PER_TABLE * 2 + 2)} statements`);
