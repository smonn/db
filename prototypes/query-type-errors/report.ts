// PROTOTYPE for #656: runs tsc and prints each probe's error under its case label.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const here = import.meta.dirname;
const root = `${here}/../..`;

function tsc(): string {
  try {
    return execFileSync(`${root}/node_modules/.bin/tsc`, ["-p", here, "--pretty", "false"], {
      encoding: "utf8",
    });
  } catch (error) {
    return (error as { stdout: string }).stdout;
  }
}

const probeLines = readFileSync(`${here}/probes.ts`, "utf8").split("\n");
const labelOf = (line: number): string => {
  const above = probeLines[line - 2] ?? "";
  return above.trim().replace("// case: ", "");
};

const errors = new Map<string, string[]>();
let current: string[] | undefined;
for (const line of tsc().split("\n")) {
  const head = /^(.+?)\((\d+),\d+\): error (TS\d+): (.*)$/.exec(line);
  if (head) {
    const [, file = "", row = "0", code, message] = head;
    const key = file.endsWith("probes.ts") ? labelOf(Number(row)) : `${file}:${row}`;
    current = [`${code}: ${message}`];
    errors.set(key, [...(errors.get(key) ?? []), ...current]);
  } else if (current && line.trim() !== "") {
    errors.get([...errors.keys()].at(-1) ?? "")?.push(line);
  }
}

const cases = probeLines
  .filter((line) => line.trim().startsWith("// case: "))
  .map((line) => line.trim().replace("// case: ", ""));
const out = cases.map((label) => {
  const text = errors.get(label)?.join("\n") ?? "NO ERROR (the bad call type-checks)";
  return `### ${label}\n\n\`\`\`\n${text}\n\`\`\`\n`;
});
const other = [...errors.keys()].filter((key) => !cases.includes(key));
const extra = other.map((key) => `### ${key}\n\n\`\`\`\n${errors.get(key)?.join("\n")}\n\`\`\`\n`);
const report = [...out, ...(extra.length > 0 ? ["## Failed checks\n", ...extra] : [])].join("\n");
writeFileSync(
  `${here}/errors.md`,
  `# Probe errors\n\nGenerated by \`node report.ts\`.\n\n${report}`,
);
console.log(report);
